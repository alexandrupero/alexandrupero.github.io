// Regenerates src/icons.ts with only the icons actually used.
// Run with: pnpm icons
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ICONS = [
  'mdi:console',
  'simple-icons:matrix',
  'uil:github-alt',
  'uil:linkedin-alt',
]

const loadCollection = (prefix) =>
  JSON.parse(
    readFileSync(
      fileURLToPath(
        new URL(
          `../node_modules/@iconify-json/${prefix}/icons.json`,
          import.meta.url,
        ),
      ),
      'utf8',
    ),
  )

const resolveIcon = (collection, name) => {
  if (collection.icons[name]) {
    return { ...collection, ...collection.icons[name] }
  }

  const alias = collection.aliases?.[name]
  if (!alias) throw new Error(`Icon not found: ${name}`)

  const parent = collection.icons[alias.parent] ?? {}
  return { ...collection, ...parent, ...alias }
}

const collections = {}
const entries = ICONS.map((fullName) => {
  const [prefix, name] = fullName.split(':')
  collections[prefix] ??= loadCollection(prefix)

  const icon = resolveIcon(collections[prefix], name)
  const data = { body: icon.body }
  if (icon.width) data.width = icon.width
  if (icon.height) data.height = icon.height

  return [`'${fullName}'`, data]
})

const body = entries
  .map(([name, data]) => `  ${name}: ${JSON.stringify(data)},`)
  .join('\n')

const output = `// AUTO-GENERATED by scripts/generate-icons.mjs — do not edit manually.
// Run \`pnpm icons\` after changing the icon list.
import { addIcon, type IconifyIcon } from '@iconify/vue'

const icons: Record<string, IconifyIcon> = {
${body}
}

for (const [name, data] of Object.entries(icons)) {
  addIcon(name, data)
}
`

writeFileSync(
  fileURLToPath(new URL('../src/icons.ts', import.meta.url)),
  output,
)

console.log(`Generated src/icons.ts with ${entries.length} icons`)
